public class _02_datatype {
  /*Primitive Data Types:

byte: 8-bit integer, range -128 to 127
short: 16-bit integer, range -32,768 to 32,767
int: 32-bit integer, range -2^31 to 2^31-1
long: 64-bit integer, range -2^63 to 2^63-1
float: 32-bit floating-point number
double: 64-bit floating-point number
char: 16-bit Unicode character
boolean: true or false
Non-Primitive Data Types:

Strings, Arrays, Classes, Interfaces, etc.
Can store multiple values or objects and have methods.
Primitive types are predefined by Java and store simple values, while non-primitive types are created by the programmer and can store complex data. */
  public static void main(String[] args) {
    //Java has 8 different Datatypes
    // byte short int float long double boolean char
    byte a = 127;
    short b = 32000;
    int c = 6400000;
    double d = 4.0; 
    char ch= 'A';

    System.out.println("byte value is :"+a);
    System.out.println("short value is :"+b);
    System.out.println("int value is :"+c);
    System.out.println("double value is :"+d);
    System.out.println("char value is :"+ch);
    






  }
}
